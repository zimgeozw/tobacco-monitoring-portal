<?php
/**
 * One-time installer: writes config.php, creates tables and the administrator account.
 * It refuses to run once config.php exists.
 */
define('INSTALLER', true);
require __DIR__ . '/app/bootstrap.php';

if ($GLOBALS['__config'] !== null) {
    http_response_code(403);
    exit('The portal is already installed. To reinstall, delete config.php on the server first.');
}

$errors = [];
$v = array_merge([
    'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
    'base_url' => (((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http') . '://' . ($_SERVER['HTTP_HOST'] ?? 'timb.zimgeo.co.zw') . rtrim(base_path_guess(), '/')),
    'admin_name' => 'Aldridge Mazhindu', 'admin_email' => '', 'admin_pass' => '',
    'smtp_host' => 'mail.zimgeo.co.zw', 'smtp_port' => '465', 'smtp_secure' => 'ssl', 'smtp_user' => 'noreply@zimgeo.co.zw', 'smtp_pass' => '',
    'from_email' => 'noreply@zimgeo.co.zw', 'from_name' => 'TIMB Tobacco Monitoring Portal',
], array_map(fn($x) => is_string($x) ? trim($x) : $x, $_POST));

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Enter a valid administrator email.';
    }
    if ($e = validate_password((string)$v['admin_pass'])) {
        $errors[] = 'Administrator password: ' . $e;
    }
    foreach (['storage', 'storage/uploads', 'storage/cache', 'storage/logs'] as $d) {
        if (!is_dir(APP_ROOT . "/$d")) {
            @mkdir(APP_ROOT . "/$d", 0755, true);
        }
        if (!is_writable(APP_ROOT . "/$d")) {
            $errors[] = "Folder $d is not writable by PHP.";
        }
    }
    if (!is_writable(APP_ROOT)) {
        $errors[] = 'The portal folder is not writable, so config.php cannot be created. Create it manually from config.sample.php.';
    }
    if (!class_exists('ZipArchive')) {
        $errors[] = 'The PHP zip extension is required for Excel export (enable it in cPanel → Select PHP Version → Extensions).';
    }
    if (!$errors) {
        try {
            $pdo = new PDO(sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $v['db_host'], (int)$v['db_port'], $v['db_name']),
                $v['db_user'], $v['db_pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $sql = file_get_contents(APP_ROOT . '/sql/schema.sql');
            foreach (array_filter(array_map('trim', preg_split('/;\s*\n/', preg_replace('/^--.*$/m', '', $sql)))) as $stmt) {
                $pdo->exec($stmt);
            }
            $exists = $pdo->prepare('SELECT id FROM users WHERE email = ?');
            $exists->execute([mb_strtolower($v['admin_email'])]);
            if (!$exists->fetch()) {
                $pdo->prepare("INSERT INTO users (name, email, role, status, password_hash, can_download, created_at) VALUES (?,?,'admin','active',?,1,NOW())")
                    ->execute([$v['admin_name'], mb_strtolower($v['admin_email']), password_hash($v['admin_pass'], PASSWORD_DEFAULT)]);
            }
            $config = [
                'app_name' => 'Tobacco Crop Monitoring Portal',
                'base_url' => rtrim($v['base_url'], '/'),
                'debug' => false,
                'db' => ['host' => $v['db_host'], 'port' => (int)$v['db_port'], 'name' => $v['db_name'], 'user' => $v['db_user'], 'pass' => $v['db_pass']],
                'mail' => [
                    'host' => $v['smtp_host'], 'port' => (int)$v['smtp_port'], 'secure' => $v['smtp_secure'],
                    'user' => $v['smtp_user'], 'pass' => $v['smtp_pass'], 'verify_ssl' => false,
                    'from_email' => $v['from_email'], 'from_name' => $v['from_name'], 'reply_to' => $v['admin_email'],
                ],
            ];
            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Not tracked in Git.\nreturn " . var_export($config, true) . ";\n";
            if (file_put_contents(APP_ROOT . '/config.php', $php) === false) {
                throw new RuntimeException('Could not write config.php');
            }
            @chmod(APP_ROOT . '/config.php', 0640);
            header('Location: ' . rtrim(base_path_guess(), '/') . '/login.php');
            exit;
        } catch (Throwable $ex) {
            $errors[] = 'Setup failed: ' . $ex->getMessage();
        }
    }
}

auth_header('Install');
?>
<h1>Set up the portal</h1>
<p class="muted">Create a MySQL database and user in cPanel (MySQL® Databases) first, then fill in the details below. This page disables itself after setup.</p>
<?php foreach ($errors as $er): ?><div class="flash error"><?= e($er) ?></div><?php endforeach; ?>
<form method="post" class="form" autocomplete="off">
  <fieldset><legend>Database</legend>
    <div class="row2"><label>Host <input name="db_host" value="<?= e($v['db_host']) ?>" required></label>
    <label>Port <input name="db_port" value="<?= e($v['db_port']) ?>" required></label></div>
    <label>Database name <input name="db_name" value="<?= e($v['db_name']) ?>" placeholder="zimgeoco_timb" required></label>
    <div class="row2"><label>User <input name="db_user" value="<?= e($v['db_user']) ?>" required></label>
    <label>Password <input type="password" name="db_pass" value="<?= e($v['db_pass']) ?>"></label></div>
  </fieldset>
  <fieldset><legend>Portal</legend>
    <label>Portal address <input name="base_url" value="<?= e($v['base_url']) ?>" required></label>
  </fieldset>
  <fieldset><legend>Administrator</legend>
    <label>Name <input name="admin_name" value="<?= e($v['admin_name']) ?>" required></label>
    <label>Email <input type="email" name="admin_email" value="<?= e($v['admin_email']) ?>" required></label>
    <label>Password <input type="password" name="admin_pass" required minlength="8" autocomplete="new-password"></label>
  </fieldset>
  <fieldset><legend>Outgoing email (SMTP)</legend>
    <p class="muted small">Create an email account in cPanel (e.g. noreply@zimgeo.co.zw). Leave host empty to use the server's PHP mail().</p>
    <div class="row2"><label>SMTP host <input name="smtp_host" value="<?= e($v['smtp_host']) ?>"></label>
    <label>Port <input name="smtp_port" value="<?= e($v['smtp_port']) ?>"></label></div>
    <label>Security <select name="smtp_secure"><option value="ssl" <?= $v['smtp_secure'] === 'ssl' ? 'selected' : '' ?>>SSL (port 465)</option><option value="tls" <?= $v['smtp_secure'] === 'tls' ? 'selected' : '' ?>>STARTTLS (port 587)</option></select></label>
    <div class="row2"><label>Username <input name="smtp_user" value="<?= e($v['smtp_user']) ?>"></label>
    <label>Password <input type="password" name="smtp_pass" value="<?= e($v['smtp_pass']) ?>"></label></div>
    <div class="row2"><label>From email <input name="from_email" value="<?= e($v['from_email']) ?>"></label>
    <label>From name <input name="from_name" value="<?= e($v['from_name']) ?>"></label></div>
  </fieldset>
  <button class="btn primary block" type="submit">Install portal</button>
</form>
<?php auth_footer();
